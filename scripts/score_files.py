class ScoreResult(NamedTuple):
    """Output of any scoring path (prefilter, oversized-skip, config-cap, llm-path, llm-content)."""
    score: int
    scored_by: str
    rationale: str
    signals: dict


def build_cold_prefix_matcher(profile: dict) -> Callable[[str], str | None]:
    """Return a function path -> matched cold prefix, or None.

    Prefixes from profile are sorted longest-first so that the most specific
    prefix wins when multiple match. The signals_json `rule` field then names
    the actual matching prefix, which is informative for debugging
    misclassifications.
    """
    prefixes = sorted(
        (p for p in profile.get("cold_path_prefixes", []) if p),
        key=len,
        reverse=True,
    )

    def _match(path: str) -> str | None:
        normalized = path.lower()
        for prefix in prefixes:
            if normalized.startswith(prefix.lower()):
                return prefix
        return None

    return _match


def prefilter_file(row, cold_matcher: Callable[[str], str | None]) -> ScoreResult | None:
    """Apply deterministic pre-filter rules. Return ScoreResult if any rule
    fires, else None (file goes to LLM scoring).

    Rule order matches the design spec:
      1. cold-prefix:<prefix>  — repo_profile.cold_path_prefixes match
      2. category:<category>   — inventory category in {docs, asset, metadata}
      3. non-text              — is_binary=1, or not code and extension not in TEXT_EXTENSIONS
    """
    cold = cold_matcher(row["path"])
    if cold is not None:
        return ScoreResult(
            score=1, scored_by="prefilter", rationale="",
            signals={"source": "prefilter", "rule": f"cold-prefix:{cold}"},
        )

    category = row["category"]
    if category in ("docs", "asset", "metadata"):
        return ScoreResult(
            score=1, scored_by="prefilter", rationale="",
            signals={"source": "prefilter", "rule": f"category:{category}"},
        )

    if row["is_binary"] or (
        category != "code" and row["extension"] and row["extension"] not in TEXT_EXTENSIONS
    ):
        return ScoreResult(
            score=1, scored_by="prefilter", rationale="",
            signals={"source": "prefilter", "rule": "non-text"},
        )

    return None


TEXT_EXTENSIONS = CODE_EXTENSIONS | {".json", ".yaml", ".yml", ".toml", ".ini", ".cfg", ".conf", ".txt", ".md", ".rst", ".adoc"}
# Pure-config / data-file extensions. These can host real findings
# (overly permissive defaults, hardcoded secrets, weak crypto choices)
# but the current worker prompt is scoped to code-bug analysis and
# can't review them well — running a worker on a .conf file produces
# a runaway breadth-first repo grep that exhausts its time budget. Hard-cap
# their priority at 2 so they don't reach the worker queue. Lift the
# cap once we have a config-specific worker prompt.
PURE_CONFIG_EXTENSIONS = {".conf", ".cnf", ".cfg", ".ini", ".properties"}

DEFAULT_SAMPLE_BYTES = 4096

# Per-file content budget passed to the phase-2 LLM batch prompt. The sample
# is head + middle + tail slices of DEFAULT_SAMPLE_BYTES each (12K), cut here
# to 8K to keep batch token cost steady, so for files over 4K only the head
# and middle slices reach the model. Bumping past 4K materially
# closed the read_config.py / sbe18.py demotion regressions where the
# dangerous code lived past the sampled head slice.
PHASE2_PER_FILE_CONTENT_BYTES = 8192

# Default batch size for phase 2. Halved from the original 10 to keep the
# batch token budget flat after PHASE2_PER_FILE_CONTENT_BYTES doubled.
DEFAULT_PHASE2_BATCH_SIZE = 5

# Production-source code extensions for the phase-2 demotion floor. If
# phase 1 (path-only) said >= 3 for a file with one of these extensions,
# phase 2's content sample alone cannot demote it below 3. Mirrors the
# phase 2 prompt's own "production source MUST NOT drop below 3" rule
# but enforced in code so the LLM can't violate it.
PRODUCTION_CODE_EXTENSIONS = CODE_EXTENSIONS

# Hard ceiling on file size for LLM scoring. Above this, emit a deterministic
# score=3 / scored_by="oversized-skip" without an LLM call. The ceiling is
# defensive against autogenerated blobs slipping past prefilter (giant SQL
# dumps, vendored minified bundles missed by name heuristics) — those would
# both burn tokens and risk crowding the scorer's accurate-zone window on
# a 64K-context model. Real production source files (even monolithic
# Django views modules) sit comfortably below this.
DEFAULT_OVERSIZED_SKIP_BYTES = 256_000

# Number of paths per retry sub-batch when phase 1 drops paths from the
# initial large batches.
RETRY_SUB_BATCH = 25


def read_content_sample(path: Path, size_bytes: int, slice_bytes: int) -> dict:
    if size_bytes <= 0:
        return {"sampled": False, "sample_bytes": 0, "text": ""}

    if size_bytes <= slice_bytes:
        raw = path.read_bytes()
        text = raw.decode("utf-8", errors="ignore")
        return {"sampled": True, "sample_bytes": len(raw), "text": text}

    offsets = [0, max(0, size_bytes // 2 - slice_bytes // 2), max(0, size_bytes - slice_bytes)]
    fragments: list[str] = []
    seen_offsets = set()

    with path.open("rb") as handle:
        for offset in offsets:
            if offset in seen_offsets:
                continue
            seen_offsets.add(offset)
            handle.seek(offset)
            fragment = handle.read(slice_bytes)
            if fragment:
                fragments.append(fragment.decode("utf-8", errors="ignore"))

    return {
        "sampled": bool(fragments),
        "sample_bytes": min(size_bytes, len(fragments) * slice_bytes),
        "text": "\n".join(fragments),
    }


def _format_repo_layout_block(analysis: dict | None) -> str:
    """Build the '## This Repository's Layout' section or return '' if no analysis."""
    if not analysis:
        return ""
    def fmt(paths: list[str]) -> str:
        return ", ".join(paths) if paths else "(none identified)"
    rationale = analysis.get("rationale", "").strip()
    rationale_line = f"\nContext: {rationale}\n" if rationale else ""
    return (
        "## This Repository's Layout\n\n"
        f"Production code (rank by content, up to 5): {fmt(analysis.get('production_paths', []))}\n"
        f"Test code (rank 1-2): {fmt(analysis.get('test_paths', []))}\n"
        f"CI config (rank 1): {fmt(analysis.get('ci_paths', []))}\n"
        f"Documentation (rank 1): {fmt(analysis.get('docs_paths', []))}\n"
        f"Developer tooling (rank 1-2): {fmt(analysis.get('tooling_paths', []))}\n"
        f"Generated code (rank 1): {fmt(analysis.get('generated_paths', []))}"
        f"{rationale_line}\n"
    )


def parse_score_output(output: str, valid_paths: set[str]) -> dict[str, dict]:
    """Parse LLM scoring output into {path: {score, rationale}}.

    Accepts two line shapes, auto-detected per line:
      - Pipe-delimited: ``score|path|rationale``
      - JSON object (fallback): ``{"path": "...", "score": N, "rationale": "..."}``

    Lines that don't match either shape are silently skipped — forgiving
    against partial output or stray prose.
    """
    import json as _json

    results: dict[str, dict] = {}
    for raw_line in output.strip().split("\n"):
        line = raw_line.strip()
        if not line:
            continue

        # JSON object shape — fallback for models that emit per-line JSON.
        if line.startswith("{") and line.endswith("}"):
            try:
                obj = _json.loads(line)
            except (ValueError, _json.JSONDecodeError):
                obj = None
            if isinstance(obj, dict):
                path = str(obj.get("path", "")).strip()
                if path not in valid_paths:
                    continue
                try:
                    score = int(obj.get("score"))
                except (TypeError, ValueError):
                    continue
                score = max(1, min(5, score))
                rationale = str(obj.get("rationale", "")).strip()
                results[path] = {"score": score, "rationale": rationale}
                continue

        # Pipe-delimited shape.
        if "|" not in line:
            continue
        parts = line.split("|", 2)
        if len(parts) < 2:
            continue
        try:
            score = int(parts[0].strip())
        except ValueError:
            continue
        path = parts[1].strip()
        if path not in valid_paths:
            continue
        score = max(1, min(5, score))
        rationale = parts[2].strip() if len(parts) > 2 else ""
        results[path] = {"score": score, "rationale": rationale}
    return results


def run_llm_scorer(prompt: str, args) -> str:
    """One scoring call against the run's endpoint/model ('' on failure)."""
    return llm.chat(
        prompt, endpoint=args.endpoint, model=args.model,
        api_key=os.environ.get("RVH_API_KEY"), timeout=3000, label="score",
    )


def llm_score_phase1(
    *,
    paths: list[str],
    args,
    repo_analysis: dict | None,
    debug_dir: Path | None = None,
) -> dict[str, dict]:
    """Phase 1: score every path from path alone, batched across the LLM.

    Batches of ``args.phase1_batch_size`` paths are dispatched concurrently
    through a ``ThreadPoolExecutor(max_workers=args.concurrency)``. Each
    batch is one LLM call returning JSONL or pipe-delimited score lines.
    Paths the model drops from large batches are retried in 25-path
    sub-batches (also concurrent). Residual misses default to score 3.

    Returns ``{path: {"score": int, "rationale": str}}`` for every input path.
    """
    if not paths:
        return {}

    layout_block = _format_repo_layout_block(repo_analysis)
    layout_section = f"\n{layout_block}\n" if layout_block else ""

    def _render(batch: list[str]) -> str:
        return load_prompt(
            "score_phase1",
            layout_section=layout_section,
            path_list="\n".join(batch),
        )

    def _call_batch(batch: list[str]) -> tuple[list[str], dict[str, dict]]:
        prompt = _render(batch)
        if debug_dir is not None:
            flat = f"phase1-batch-{abs(hash(tuple(batch))) % 10**8:08d}"
            debug_log(debug_dir, "score", f"{flat}-input", prompt)
        output = run_llm_scorer(prompt, args)
        if debug_dir is not None:
            debug_log(debug_dir, "score", f"{flat}-output", output)
        return batch, parse_score_output(output, set(batch))

    # Initial batches
    batch_size = max(1, int(getattr(args, "phase1_batch_size", 100)))
    initial_batches = [paths[i:i + batch_size] for i in range(0, len(paths), batch_size)]
    print(
        f"[rvh] Phase 1: {len(paths)} paths in {len(initial_batches)} "
        f"batches of {batch_size} (concurrency={args.concurrency})",
        file=sys.stderr, flush=True,
    )

    results: dict[str, dict] = {}
    with ThreadPoolExecutor(max_workers=max(1, args.concurrency)) as pool:
        futures = [pool.submit(_call_batch, b) for b in initial_batches]
        for done, fut in enumerate(as_completed(futures), start=1):
            try:
                _, parsed = fut.result()
            except Exception as exc:
                print(
                    f"[rvh] Phase 1 batch failed: {exc}",
                    file=sys.stderr, flush=True,
                )
                parsed = {}
            results.update(parsed)
            if done % 5 == 0 or done == len(futures):
                print(
                    f"[rvh] Phase 1: {done}/{len(futures)} batches complete "
                    f"({len(results)}/{len(paths)} scored)",
                    file=sys.stderr, flush=True,
                )

    # Retry pass — sub-batches of RETRY_SUB_BATCH for any path the initial pass dropped
    missed = [p for p in paths if p not in results]
    if missed:
        sub_size = RETRY_SUB_BATCH
        sub_batches = [missed[i:i + sub_size] for i in range(0, len(missed), sub_size)]
        print(
            f"[rvh] Phase 1: retrying {len(missed)} dropped paths in "
            f"{len(sub_batches)} sub-batches of {sub_size}",
            file=sys.stderr, flush=True,
        )
        with ThreadPoolExecutor(max_workers=max(1, args.concurrency)) as pool:
            futures = [pool.submit(_call_batch, b) for b in sub_batches]
            for fut in as_completed(futures):
                try:
                    _, parsed = fut.result()
                except Exception as exc:
                    print(
                        f"[rvh] Phase 1 retry batch failed: {exc}",
                        file=sys.stderr, flush=True,
                    )
                    parsed = {}
                results.update(parsed)

    # Default any still-missed paths to score 3
    still_missed = [p for p in paths if p not in results]
    for p in still_missed:
        results[p] = {"score": 3, "rationale": ""}
    if still_missed:
        print(
            f"[rvh] Phase 1: {len(still_missed)} paths defaulted to score 3 "
            f"after retry exhausted",
            file=sys.stderr, flush=True,
        )

    return results


def llm_score_phase2(
    *,
    phase1_results: dict[str, dict],
    sizes_by_path: dict[str, int],
    repo_root: Path,
    args,
    repo_analysis: dict | None,
    threshold: int = 2,
    debug_dir: Path | None = None,
) -> dict[str, dict]:
    """Phase 2: re-score phase-1 survivors using their actual content.

    Only paths with phase-1 score >= ``threshold`` enter phase 2. Each one
    is sampled (head/middle/tail per ``args.sample_bytes``, then cut to
    PHASE2_PER_FILE_CONTENT_BYTES to keep batch prompts tractable). Files are batched
    ``args.phase2_batch_size`` per LLM call, with batches dispatched
    concurrently via a thread pool. Drops are retried in one small batch.

    Returns ``{path: {"score": int, "rationale": str}}`` for every path
    that entered phase 2 (callers should retain phase-1 scores for any path
    missing from the output — that includes both files filtered below threshold
    and any paths whose batch raised an exception that exhausted the retry pass).
    """
    candidates = sorted(p for p, data in phase1_results.items()
                        if data.get("score", 0) >= threshold)
    if not candidates:
        return {}

    files_with_content: list[dict] = []
    for path in candidates:
        full_path = repo_root / path
        if not full_path.is_file():
            continue
        size = sizes_by_path.get(path)
        if size is None:
            continue
        sample = read_content_sample(full_path, size, args.sample_bytes)
        if not sample["sampled"]:
            continue
        files_with_content.append({
            "path": path,
            "content": sample["text"][:PHASE2_PER_FILE_CONTENT_BYTES],
        })

    if not files_with_content:
        return {}

    layout_block = _format_repo_layout_block(repo_analysis)
    layout_section = f"\n{layout_block}\n" if layout_block else ""

    def _render(batch: list[dict]) -> str:
        files_section = "\n\n".join(
            f"### {entry['path']}\n```\n{entry['content']}\n```"
            for entry in batch
        )
        return load_prompt(
            "score_phase2",
            layout_section=layout_section,
            files_section=files_section,
        )

    def _call_batch(batch: list[dict]) -> dict[str, dict]:
        prompt = _render(batch)
        valid_paths = {e["path"] for e in batch}
        if debug_dir is not None:
            flat = f"phase2-batch-{abs(hash(tuple(sorted(valid_paths)))) % 10**8:08d}"
            debug_log(debug_dir, "score", f"{flat}-input", prompt)
        output = run_llm_scorer(prompt, args)
        if debug_dir is not None:
            debug_log(debug_dir, "score", f"{flat}-output", output)
        return parse_score_output(output, valid_paths)

    batch_size = max(1, int(getattr(args, "phase2_batch_size", DEFAULT_PHASE2_BATCH_SIZE)))
    batches = [files_with_content[i:i + batch_size]
               for i in range(0, len(files_with_content), batch_size)]
    print(
        f"[rvh] Phase 2: {len(files_with_content)} files in "
        f"{len(batches)} batches of {batch_size} "
        f"(concurrency={args.concurrency})",
        file=sys.stderr, flush=True,
    )

    results: dict[str, dict] = {}
    with ThreadPoolExecutor(max_workers=max(1, args.concurrency)) as pool:
        futures = [pool.submit(_call_batch, b) for b in batches]
        for done, fut in enumerate(as_completed(futures), start=1):
            try:
                parsed = fut.result()
            except Exception as exc:
                print(
                    f"[rvh] Phase 2 batch failed: {exc}",
                    file=sys.stderr, flush=True,
                )
                parsed = {}
            results.update(parsed)
            if done % 5 == 0 or done == len(futures):
                print(
                    f"[rvh] Phase 2: {done}/{len(futures)} batches complete "
                    f"({len(results)}/{len(files_with_content)} re-scored)",
                    file=sys.stderr, flush=True,
                )

    # Retry pass — sub-batch the drops into chunks the model can actually
    # ingest. A single mega-batch trips HTTP 400 once per-file content is 8 KB
    # (60 dropped × 8 KB ≈ 480 KB blew past the context window in coriolix
    # run 2026-05-04). Sub-batches mirror the regular batch size, dispatched
    # concurrently. Any sub-batch that still fails is logged and dropped —
    # the synthesizer falls back to the phase 1 score for missing paths.
    missed = [e for e in files_with_content if e["path"] not in results]
    if missed:
        sub_size = batch_size
        sub_batches = [missed[i:i + sub_size] for i in range(0, len(missed), sub_size)]
        print(
            f"[rvh] Phase 2: retrying {len(missed)} dropped files in "
            f"{len(sub_batches)} sub-batches of {sub_size}",
            file=sys.stderr, flush=True,
        )
        with ThreadPoolExecutor(max_workers=max(1, args.concurrency)) as pool:
            retry_futures = [pool.submit(_call_batch, b) for b in sub_batches]
            for fut in as_completed(retry_futures):
                try:
                    parsed = fut.result()
                except Exception as exc:
                    print(
                        f"[rvh] Phase 2 retry sub-batch failed: {exc}",
                        file=sys.stderr, flush=True,
                    )
                    parsed = {}
                results.update(parsed)
        still_missing = [e["path"] for e in missed if e["path"] not in results]
        if still_missing:
            print(
                f"[rvh] Phase 2: {len(still_missing)} files unrecoverable "
                f"after retry — phase 1 score will be used as fallback",
                file=sys.stderr, flush=True,
            )

    return results


def run_two_phase_llm_scorer(
    conn,
    run_dir: Path,
    repo_root: Path,
    args,
    *,
    profile: dict,
    repo_analysis: dict | None,
    debug: bool = False,
) -> dict[str, ScoreResult]:
    """Two-phase LLM scorer with deterministic pre-filter.

    Pipeline per ``excluded=0`` file:
      1. Pre-filter (cold-prefix / category / non-text / oversized / pure-config)
         → score 1 (or 3 for oversized) without an LLM call.
      2. Phase 1: surviving paths batched 100/call, dispatched concurrently;
         path-only triage produces a 1–5 score per path.
      3. Phase 2: phase-1 survivors with score >= 2 batched 10/call (with
         content samples), dispatched concurrently; final 1–5 score.

    Returns ``{path: ScoreResult}`` for every excluded=0 file. Caller
    persists to the ``scores`` and ``tasks`` tables.
    """
    rows = conn.execute(
        "SELECT id, path, extension, category, is_binary, size_bytes "
        "FROM files WHERE excluded = 0 ORDER BY path"
    ).fetchall()

    cold_matcher = build_cold_prefix_matcher(profile)
    oversized_cap = int(getattr(args, "oversized_skip_bytes", DEFAULT_OVERSIZED_SKIP_BYTES))
    debug_dir = run_dir if debug else None

    results: dict[str, ScoreResult] = {}
    phase1_paths: list[str] = []
    sizes_by_path: dict[str, int] = {}

    for row in rows:
        path = row["path"]
        sizes_by_path[path] = row["size_bytes"]

        prefilter = prefilter_file(row, cold_matcher)
        if prefilter is not None:
            results[path] = prefilter
            continue

        # Oversized-skip rule (defensive — shouldn't survive prefilter on real
        # repos, but generated blobs sometimes do).
        if row["size_bytes"] and row["size_bytes"] > oversized_cap:
            results[path] = ScoreResult(
                score=3,
                scored_by="oversized-skip",
                rationale=f"size {row['size_bytes']} exceeds scorer cap {oversized_cap}",
                signals={"source": "oversized-skip", "size_bytes": row["size_bytes"]},
            )
            continue

        # Pure-config files cap at 2 (worker prompt can't review them well).
        if row["extension"] in PURE_CONFIG_EXTENSIONS:
            results[path] = ScoreResult(
                score=2,
                scored_by="config-cap",
                rationale="pure-config extension capped at 2",
                signals={"source": "config-cap", "extension": row["extension"]},
            )
            continue

        phase1_paths.append(path)

    # Phase 1
    phase1 = llm_score_phase1(
        paths=phase1_paths,
        args=args,
        repo_analysis=repo_analysis,
        debug_dir=debug_dir,
    )

    # Phase 2 only for survivors with score >= 2
    phase2 = llm_score_phase2(
        phase1_results=phase1,
        sizes_by_path=sizes_by_path,
        repo_root=repo_root,
        args=args,
        repo_analysis=repo_analysis,
        threshold=2,
        debug_dir=debug_dir,
    )

    # Synthesize final ScoreResults from phase 1 + phase 2
    for path in phase1_paths:
        if path in phase2:
            data = phase2[path]
            phase1_score = phase1[path]["score"]
            phase2_score = data["score"]
            phase2_rationale = (data.get("rationale") or "").strip()
            phase1_rationale = (phase1[path].get("rationale") or "").strip()

            # Fix A: fall back to phase 1 rationale when phase 2 omits one,
            # instead of overwriting with empty string.
            rationale = phase2_rationale or phase1_rationale

            # Fix B: production-source floor. If phase 1 (path-only) said
            # this file is real source code (>= 3) and the extension is a
            # production code extension, phase 2's content sample alone
            # cannot demote it below 3. Codifies the phase 2 prompt's own
            # "production source MUST NOT drop below 3" rule that the LLM
            # sometimes ignores (observed P5 -> P1 demotions of Django
            # views/models in coriolix run 2026-05-04).
            ext = Path(path).suffix.lower()
            floor_applied = False
            final_score = phase2_score
            if (phase1_score >= 3
                    and phase2_score < 3
                    and ext in PRODUCTION_CODE_EXTENSIONS):
                final_score = 3
                floor_applied = True
                rationale = (
                    f"floor=3 (phase1={phase1_score}) overrides phase2 "
                    f"demotion: {rationale}"
                ) if rationale else (
                    f"floor=3 (phase1={phase1_score}) overrides phase2 demotion to {phase2_score}"
                )

            signals = {
                "source": "llm-content",
                "phase1_score": phase1_score,
                "rationale": rationale,
            }
            if floor_applied:
                signals["floor_applied"] = True
                signals["phase2_raw_score"] = phase2_score

            results[path] = ScoreResult(
                score=final_score,
                scored_by="llm-content",
                rationale=rationale,
                signals=signals,
            )
        else:
            data = phase1[path]
            results[path] = ScoreResult(
                score=data["score"],
                scored_by="llm-path",
                rationale=data.get("rationale", ""),
                signals={
                    "source": "llm-path",
                    "rationale": data.get("rationale", ""),
                },
            )

    return results


def main() -> None:
    parser = parse_common_run_arg()
    parser.add_argument(
        "--sample-bytes",
        type=int,
        default=DEFAULT_SAMPLE_BYTES,
        help="Bytes sampled per slice when content reranking",
    )
    parser.add_argument("--concurrency", type=int, default=2,
        help="Max in-flight LLM batch calls dispatched per phase (default: 2). "
             "Enough to keep a single-slot server's batching fed without "
             "overwhelming its request queue.")
    parser.add_argument("--phase1-batch-size", type=int, default=100,
        help="Paths per phase-1 LLM call (default: 100)")
    parser.add_argument("--phase2-batch-size", type=int, default=DEFAULT_PHASE2_BATCH_SIZE,
        help=f"Files per phase-2 LLM call (default: {DEFAULT_PHASE2_BATCH_SIZE})")
    parser.add_argument(
        "--oversized-skip-bytes",
        type=int,
        default=DEFAULT_OVERSIZED_SKIP_BYTES,
        help="Files larger than this skip the LLM scorer and get score=3 / "
             "scored_by=oversized-skip. Defends against generated blobs that "
             f"slip past prefilter (default: {DEFAULT_OVERSIZED_SKIP_BYTES} bytes).",
    )
    parser.add_argument("--endpoint", required=True, help="OpenAI-compatible endpoint")
    parser.add_argument("--model", required=True, help="Model name")
    parser.add_argument("--debug", action="store_true",
        help="Save LLM prompts and outputs to logs/debug/")
    args = parser.parse_args()

    run_dir = Path(args.run).expanduser().resolve()
    config = read_config(run_dir)
    profile = load_repo_profile(run_dir)
    repo_analysis = load_repo_analysis(run_dir)
    now = utc_now()
    count = 0

    with connect_db(run_dir) as conn:
        run = require_run(conn)
        repo_root = Path(conn.execute("SELECT repo_root FROM runs LIMIT 1").fetchone()["repo_root"])

        results = run_two_phase_llm_scorer(
            conn, run_dir, repo_root, args,
            profile=profile, repo_analysis=repo_analysis, debug=args.debug,
        )

        now = utc_now()
        for path, result in results.items():
            file_row = conn.execute(
                "SELECT id FROM files WHERE path = ?", (path,)
            ).fetchone()
            if not file_row:
                continue
            conn.execute(
                """INSERT INTO scores (file_id, score, rationale, signals_json, scored_by, scored_at)
                   VALUES (?, ?, ?, ?, ?, ?)
                   ON CONFLICT(file_id) DO UPDATE SET
                   score=excluded.score, rationale=excluded.rationale,
                   signals_json=excluded.signals_json, scored_by=excluded.scored_by,
                   scored_at=excluded.scored_at""",
                (file_row["id"], result.score, result.rationale,
                 json.dumps(result.signals, sort_keys=True),
                 result.scored_by, now),
            )
            conn.execute(
                "UPDATE tasks SET priority = ?, updated_at = ? WHERE file_id = ?",
                (result.score, now, file_row["id"]),
            )
            count += 1

        update_run_timestamp(conn, run["id"])
        conn.execute("UPDATE runs SET status = ? WHERE id = ?", ("scored", run["id"]))

    print(json.dumps({"scored_files": count, "run": str(run_dir)}, indent=2))


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\n[rvh] scoring interrupted", file=sys.stderr)
        raise SystemExit(1)
