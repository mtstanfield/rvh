#!/usr/bin/env python3

from __future__ import annotations

import argparse
import fnmatch
import json
from pathlib import Path

from common import connect_db, normalize_rel_path, parse_common_run_arg, read_config, require_run, update_run_timestamp, utc_now, walk_repo


DOC_EXTENSIONS = {".md", ".rst", ".txt", ".adoc"}
CONFIG_EXTENSIONS = {".json", ".yaml", ".yml", ".toml", ".ini", ".cfg", ".conf", ".xml"}
# The one list of source-code extensions: the scorer, the worker's language
# modules and the CPG maps all key off it (tests/test_extension_coverage.py).
CODE_EXTENSIONS = {
    ".c", ".cc", ".cpp", ".cxx", ".h", ".hh", ".hpp", ".hxx",
    ".rs", ".go", ".py", ".pyi", ".java", ".kt", ".kts", ".m", ".mm",
    ".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx", ".php", ".rb", ".pl", ".pm",
    ".cs", ".swift", ".scala", ".lua", ".sh", ".bash",
    # A language embedded in another format: Vue/Svelte components, PHP and
    # Ruby views, zeek's binpac parsers and builtins (C++ inside %{ %}).
    ".vue", ".svelte", ".ctp", ".phtml", ".erb", ".pac", ".bif",
}
# Extensions that are code only when the file head carries the marker:
# .inc is a PHP view partial in CakePHP apps but a make fragment elsewhere.
SNIFFED_CODE_EXTENSIONS = {".inc": "<?php"}

GENERATION_MARKERS = (
    "generated by",
    "auto-generated",
    "autogenerated",
    "code generated",
    "do not edit",
    "@generated",
)

# Filename suffixes that mark a bundled/minified asset (vendored client code,
# not first-party source). Matched case-insensitively against the rel path.
_MINIFIED_NAME_SUFFIXES = (".min.js", ".min.css", ".bundle.js", "-min.js", "-min.css")


def detect_binary(path: Path) -> bool:
    try:
        with path.open("rb") as handle:
            chunk = handle.read(4096)
    except OSError:
        return True
    if not chunk:
        return False
    return b"\x00" in chunk


def read_text_sample(path: Path, limit: int = 2048) -> str:
    try:
        with path.open("r", encoding="utf-8", errors="ignore") as handle:
            return handle.read(limit)
    except OSError:
        return ""


def is_minified(rel_path: str, sample: str) -> bool:
    """Deterministic minified/bundled-asset detector.

    True when the filename carries a minified/bundle suffix, the content
    references a source map, or the sampled content is minification-shaped
    (very long lines / low newline density). The line-density branch only
    fires on >=500-byte samples averaging >200 chars/line, which normal
    source effectively never hits — so this stays conservative and never
    flags hand-written code as vendored."""
    if rel_path.lower().endswith(_MINIFIED_NAME_SUFFIXES):
        return True
    if "sourcemappingurl" in sample.lower():
        return True
    return len(sample) >= 500 and sample.count("\n") <= len(sample) / 200


def is_generated_file(rel_path: str, path: Path) -> bool:
    lowered = rel_path.lower()
    path_parts = set(lowered.split("/"))
    gen_tokens = ("generated", "autogen", "auto_gen", "codegen")
    if any(token in lowered for token in gen_tokens) or "gen" in path_parts:
        return True
    if any(part in {"generated", "autogen", "codegen", "dist", "build", "out"} for part in path_parts):
        return True
    sample = read_text_sample(path)
    if is_minified(rel_path, sample):
        return True
    lowered_sample = sample.lower()
    return any(marker in lowered_sample for marker in GENERATION_MARKERS)


def parse_scope_paths(values: list[str], repo_root: Path) -> list[str]:
    resolved: list[str] = []
    for raw in values:
        candidate = Path(raw).expanduser()
        if candidate.is_absolute():
            resolved_path = candidate.resolve()
        else:
            resolved_path = (repo_root / candidate).resolve()
        try:
            rel = resolved_path.relative_to(repo_root).as_posix()
            if rel != ".":
                resolved.append(rel)
        except ValueError as exc:
            raise SystemExit(f"scope path {raw!r} is outside the repository root") from exc
    return sorted(set(resolved))


def matches_scope(rel_path: str, prefixes: list[str], *, empty_matches_all: bool) -> bool:
    if not prefixes:
        return empty_matches_all
    return any(rel_path == prefix or rel_path.startswith(f"{prefix}/") for prefix in prefixes)


def matches_any_glob(rel_path: str, globs: list[str]) -> bool:
    return any(fnmatch.fnmatch(rel_path, pattern) for pattern in globs)


def tag_or_exclude(policy: str, tag: str, reason: str) -> tuple[list[str], bool, str | None]:
    if policy == "include":
        return [], False, None
    if policy == "exclude":
        return [tag], True, reason
    return [tag], False, None


def categorize_file(
    rel_path: str,
    path: Path,
    extension: str,
    is_binary: bool,
    vendor_policy: str,
    generated_policy: str,
    test_policy: str,
    max_file_size: int,
) -> tuple[str, list[str], bool, str | None]:
    parts = rel_path.split("/")
    tags: list[str] = []
    excluded = False
    reason = None

    if is_binary:
        tags.append("binary")
        excluded = True
        reason = "binary file"

    if max_file_size > 0 and path.stat().st_size > max_file_size:
        return "other", tags, True, f"file exceeds max_file_size ({max_file_size} bytes)"

    if any(part.lower() in {"vendor", "third_party", "third-party", "deps", "external",
                            "bower_components", "jspm_packages", "node_modules"} for part in parts):
        new_tags, new_excluded, new_reason = tag_or_exclude(
            vendor_policy, "vendored", "vendored file excluded by vendor policy"
        )
        tags.extend(new_tags)
        excluded = excluded or new_excluded
        reason = reason or new_reason

    if any(part.lower() in {"test", "tests", "testing", "fixtures", "examples", "docs", "doc"} for part in parts):
        new_tags, new_excluded, new_reason = tag_or_exclude(
            test_policy, "support", "test/support file excluded by test policy"
        )
        tags.extend(new_tags)
        excluded = excluded or new_excluded
        reason = reason or new_reason

    if is_generated_file(rel_path, path):
        new_tags, new_excluded, new_reason = tag_or_exclude(
            generated_policy, "generated", "generated file excluded by generated policy"
        )
        tags.extend(new_tags)
        excluded = excluded or new_excluded
        reason = reason or new_reason

    if extension in DOC_EXTENSIONS:
        return "docs", tags, True, reason or "documentation"
    if extension in CONFIG_EXTENSIONS:
        return "config", tags, excluded, reason
    if extension in CODE_EXTENSIONS:
        return "code", tags, excluded, reason
    marker = SNIFFED_CODE_EXTENSIONS.get(extension)
    if marker and marker in read_text_sample(path):
        return "code", tags, excluded, reason
    if extension in {".svg", ".png", ".jpg", ".jpeg", ".gif", ".pdf"}:
        return "asset", tags, True, reason or "asset file"
    if extension in {".lock", ".sum"}:
        return "metadata", tags, True, reason or "dependency metadata"

    return "other", tags, excluded, reason


def main() -> None:
    parser = parse_common_run_arg()
    args = parser.parse_args()

    run_dir = Path(args.run).expanduser().resolve()
    config = read_config(run_dir)
    repo_root = Path(config["repo_root"])
    include_paths = parse_scope_paths(config.get("include_paths", []), repo_root)
    exclude_paths = parse_scope_paths(config.get("exclude_paths", []), repo_root)
    exclude_globs = [item for item in config.get("exclude_globs", []) if item]

    inserted = 0
    updated = 0
    skipped = 0
    seen_paths: set[str] = set()
    now = utc_now()
    vendor_policy = config.get("vendor_policy", "deprioritize")
    generated_policy = config.get("generated_policy", "deprioritize")
    test_policy = config.get("test_policy", "deprioritize")
    max_file_size = int(config.get("max_file_size", 0) or 0)

    with connect_db(run_dir) as conn:
        run = require_run(conn)
        for path in walk_repo(repo_root):
            if not path.is_file():
                continue
            rel_path = normalize_rel_path(path, repo_root)
            if not matches_scope(rel_path, include_paths, empty_matches_all=True):
                skipped += 1
                continue
            if matches_scope(rel_path, exclude_paths, empty_matches_all=False) or matches_any_glob(rel_path, exclude_globs):
                skipped += 1
                continue
            seen_paths.add(rel_path)
            extension = path.suffix.lower()
            size_bytes = path.stat().st_size
            is_binary = detect_binary(path)
            category, tags, excluded, reason = categorize_file(
                rel_path,
                path,
                extension,
                is_binary,
                vendor_policy,
                generated_policy,
                test_policy,
                max_file_size,
            )
            rel_parent = Path(rel_path).parent
            rel_dir = "/" if str(rel_parent) == "." else rel_parent.as_posix()
            row = conn.execute("SELECT id FROM files WHERE path = ?", (rel_path,)).fetchone()
            payload = (
                rel_path,
                rel_dir or "/",
                extension,
                size_bytes,
                1 if is_binary else 0,
                category,
                json.dumps(sorted(set(tags))),
                1 if excluded else 0,
                reason,
                now,
            )
            if row is None:
                conn.execute(
                    """
                    INSERT INTO files
                    (path, rel_dir, extension, size_bytes, is_binary, category, tags_json, excluded, exclusion_reason, created_at, updated_at)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """,
                    payload + (now,),
                )
                file_id = conn.execute("SELECT id FROM files WHERE path = ?", (rel_path,)).fetchone()["id"]
                # Only schedule a worker task for files we'll actually analyze.
                # Excluded files (binary, oversize, docs, assets) would otherwise
                # sit in `pending` forever, polluting progress counts.
                if not excluded:
                    conn.execute(
                        """
                        INSERT INTO tasks (file_id, priority, status, created_at, updated_at)
                        VALUES (?, ?, ?, ?, ?)
                        """,
                        (file_id, 1, "pending", now, now),
                    )
                inserted += 1
            else:
                file_id = row["id"]
                conn.execute(
                    """
                    UPDATE files
                    SET rel_dir = ?, extension = ?, size_bytes = ?, is_binary = ?, category = ?, tags_json = ?,
                        excluded = ?, exclusion_reason = ?, updated_at = ?
                    WHERE path = ?
                    """,
                    (
                        rel_dir or "/",
                        extension,
                        size_bytes,
                        1 if is_binary else 0,
                        category,
                        json.dumps(sorted(set(tags))),
                        1 if excluded else 0,
                        reason,
                        now,
                        rel_path,
                    ),
                )
                if excluded:
                    # File is (now) excluded — bump any non-terminal task to
                    # rejected so it leaves the active queue. Mirrors the
                    # outside-inventory-scope handling below.
                    conn.execute(
                        """
                        UPDATE tasks
                        SET status = CASE
                                WHEN status IN ('completed', 'rejected', 'failed') THEN status
                                ELSE 'rejected'
                            END,
                            notes = CASE
                                WHEN status IN ('completed', 'rejected', 'failed') THEN notes
                                ELSE COALESCE(?, 'file excluded from inventory')
                            END,
                            updated_at = ?
                        WHERE file_id = ?
                        """,
                        (reason, now, file_id),
                    )
                else:
                    conn.execute(
                        """
                        UPDATE tasks
                        SET status = CASE
                                WHEN status IN ('completed', 'failed', 'reserved', 'in_progress', 'needs_followup', 'requeued') THEN status
                                ELSE 'pending'
                            END,
                            notes = CASE
                                WHEN status IN ('completed', 'failed', 'reserved', 'in_progress', 'needs_followup', 'requeued') THEN notes
                                ELSE NULL
                            END,
                            updated_at = ?
                        WHERE file_id = ?
                        """,
                        (now, file_id),
                    )
                updated += 1

        if seen_paths:
            placeholders = ", ".join("?" for _ in seen_paths)
            conn.execute(
                f"""
                UPDATE files
                SET excluded = 1, exclusion_reason = 'outside current inventory scope', updated_at = ?
                WHERE path NOT IN ({placeholders})
                """,
                (now, *sorted(seen_paths)),
            )
            conn.execute(
                f"""
                UPDATE tasks
                SET status = CASE
                        WHEN status IN ('completed', 'rejected', 'failed') THEN status
                        ELSE 'rejected'
                    END,
                    notes = CASE
                        WHEN status IN ('completed', 'rejected', 'failed') THEN notes
                        ELSE 'outside current inventory scope'
                    END,
                    updated_at = ?
                WHERE file_id IN (
                    SELECT id FROM files WHERE path NOT IN ({placeholders})
                )
                """,
                (now, *sorted(seen_paths)),
            )
        else:
            conn.execute(
                """
                UPDATE files
                SET excluded = 1, exclusion_reason = 'outside current inventory scope', updated_at = ?
                """,
                (now,),
            )
            conn.execute(
                """
                UPDATE tasks
                SET status = CASE
                        WHEN status IN ('completed', 'rejected', 'failed') THEN status
                        ELSE 'rejected'
                    END,
                    notes = CASE
                        WHEN status IN ('completed', 'rejected', 'failed') THEN notes
                        ELSE 'outside current inventory scope'
                    END,
                    updated_at = ?
                """,
                (now,),
            )
        update_run_timestamp(conn, run["id"])
        conn.execute("UPDATE runs SET status = ? WHERE id = ?", ("inventoried", run["id"]))

    print(json.dumps({"inserted": inserted, "updated": updated, "skipped": skipped, "run": str(run_dir)}, indent=2))


if __name__ == "__main__":
    main()
